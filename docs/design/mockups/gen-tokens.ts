// Emits tokens.css from the generated Swift theme so the mockups and IrisUI/Theme share one source.
// Run: bun docs/design/mockups/gen-tokens.ts
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(
  new URL("../../../apple/Packages/IrisUI/Sources/IrisUI/Theme/BasaltTokens.generated.swift", import.meta.url),
  "utf8",
);
const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const rgba = (r: string, g: string, b: string, a: string) => {
  const c = (v: string) => Math.round(Number(v) * 255);
  return Number(a) === 1 ? `rgb(${c(r)} ${c(g)} ${c(b)})` : `rgb(${c(r)} ${c(g)} ${c(b)} / ${a})`;
};

const light: string[] = [];
const dark: string[] = [];
const re =
  /static let (\w+) = ColorPair\(\s*light: RGBA\(red: ([\d.]+), green: ([\d.]+), blue: ([\d.]+), alpha: ([\d.]+)\),\s*dark: RGBA\(red: ([\d.]+), green: ([\d.]+), blue: ([\d.]+), alpha: ([\d.]+)\)\)/g;
for (const m of src.matchAll(re)) {
  light.push(`  --${kebab(m[1]!)}: ${rgba(m[2]!, m[3]!, m[4]!, m[5]!)};`);
  dark.push(`  --${kebab(m[1]!)}: ${rgba(m[6]!, m[7]!, m[8]!, m[9]!)};`);
}
const scalars = (block: string, prefix: string) =>
  [...(src.match(new RegExp(`enum ${block} \\{([\\s\\S]*?)\\n  \\}`))?.[1] ?? "").matchAll(/static let (\w+): Double = ([\d.]+)/g)].map(
    (m) => `  --${prefix}-${kebab(m[1]!)}: ${Number(m[2])}px;`,
  );

const css = `/* GENERATED by gen-tokens.ts from BasaltTokens.generated.swift. Do not edit. */
:root {
${light.join("\n")}
${scalars("Radius", "radius").join("\n")}
${scalars("Spacing", "space").join("\n")}
${scalars("TextSize", "text").join("\n")}
}
[data-scheme="dark"] {
${dark.join("\n")}
}
`;
writeFileSync(new URL("./tokens.css", import.meta.url), css);
console.log(`tokens.css: ${light.length} colors`);
